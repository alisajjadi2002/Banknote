# ==================== GIF GENERATION ====================

def create_matching_gif(
    results,
    output_path=None,
    duration=GIF_DURATION
):
    if output_path is None:
        output_path = OUTPUT_GIF_PATH

    os.makedirs(
        os.path.dirname(output_path) or ".",
        exist_ok=True
    )

    canvas_width = GIF_MAX_WIDTH
    canvas_height = GIF_MAX_HEIGHT

    header_height = 75
    footer_height = 65
    gap = 30

    panel_width = (canvas_width - 3 * gap) // 2
    panel_height = canvas_height - header_height - footer_height - 2 * gap

    frames = []

    try:
        title_font = ImageFont.truetype(
            "DejaVuSans.ttf",
            23
        )

        font = ImageFont.truetype(
            "DejaVuSans.ttf",
            16
        )

        small_font = ImageFont.truetype(
            "DejaVuSans.ttf",
            12
        )

    except OSError:
        title_font = ImageFont.load_default()
        font = ImageFont.load_default()
        small_font = ImageFont.load_default()

    def load_rgb(path):
        image = cv2.imread(path)

        if image is None:
            return None

        image = cv2.cvtColor(
            image,
            cv2.COLOR_BGR2RGB
        )

        return Image.fromarray(image)

    def fit_image(image, max_width, max_height):
        image = image.copy()

        image.thumbnail(
            (max_width, max_height),
            Image.Resampling.LANCZOS
        )

        return image

    def shorten(text, max_length=42):
        if len(text) <= max_length:
            return text

        return text[:max_length - 3] + "..."

    valid_results = [
        result
        for result in results
        if result.get("old_image")
    ]

    if not valid_results:
        raise ValueError(
            "No valid matching results available for GIF generation."
        )

    total_results = len(valid_results)

    for index, result in enumerate(valid_results, start=1):
        old_image = load_rgb(result["old_image"])

        if old_image is None:
            print(
                f"Skipping unreadable old image: "
                f"{result['old_image']}"
            )
            continue

        new_image = None

        if result.get("new_image") is not None:
            new_image = load_rgb(result["new_image"])

        frame = Image.new(
            "RGB",
            (canvas_width, canvas_height),
            (248, 249, 252)
        )

        draw = ImageDraw.Draw(frame)

        draw.text(
            (gap, 18),
            "BANKNOTE MATCHING",
            fill=(25, 35, 55),
            font=title_font
        )

        draw.text(
            (canvas_width - 230, 25),
            f"Result {index} / {total_results}",
            fill=(75, 85, 105),
            font=font
        )

        old_panel_x = gap
        new_panel_x = 2 * gap + panel_width
        panel_y = header_height

        old_name = shorten(
            os.path.basename(result["old_image"])
        )

        new_name = (
            shorten(os.path.basename(result["new_image"]))
            if result.get("new_image")
            else "No confident match"
        )

        draw.text(
            (old_panel_x, panel_y),
            f"OLD: {old_name}",
            fill=(35, 45, 65),
            font=font
        )

        draw.text(
            (new_panel_x, panel_y),
            f"NEW: {new_name}",
            fill=(35, 45, 65),
            font=font
        )

        image_y = panel_y + 30
        image_area_height = panel_height - 35

        old_image = fit_image(
            old_image,
            panel_width - 12,
            image_area_height
        )

        old_x = (
            old_panel_x
            + (panel_width - old_image.width) // 2
        )

        old_y = (
            image_y
            + (image_area_height - old_image.height) // 2
        )

        frame.paste(
            old_image,
            (old_x, old_y)
        )

        if new_image is not None:
            new_image = fit_image(
                new_image,
                panel_width - 12,
                image_area_height
            )

            new_x = (
                new_panel_x
                + (panel_width - new_image.width) // 2
            )

            new_y = (
                image_y
                + (image_area_height - new_image.height) // 2
            )

            frame.paste(
                new_image,
                (new_x, new_y)
            )

        else:
            message = "NO CONFIDENT MATCH"

            bbox = draw.textbbox(
                (0, 0),
                message,
                font=font
            )

            text_width = bbox[2] - bbox[0]
            text_height = bbox[3] - bbox[1]

            draw.text(
                (
                    new_panel_x
                    + (panel_width - text_width) // 2,
                    image_y
                    + (image_area_height - text_height) // 2
                ),
                message,
                fill=(190, 45, 45),
                font=font
            )

        draw.rectangle(
            (
                old_panel_x - 5,
                panel_y - 5,
                old_panel_x + panel_width,
                image_y + image_area_height + 5
            ),
            outline=(205, 210, 220),
            width=2
        )

        draw.rectangle(
            (
                new_panel_x - 5,
                panel_y - 5,
                new_panel_x + panel_width,
                image_y + image_area_height + 5
            ),
            outline=(205, 210, 220),
            width=2
        )

        score = float(result["score"])
        status = result["status"].upper()

        draw.text(
            (gap, canvas_height - footer_height + 10),
            f"Similarity Score: {score:.3f}",
            fill=(25, 35, 55),
            font=font
        )

        status_color = (
            (35, 135, 75)
            if status == "MATCHED"
            else (190, 75, 45)
        )

        draw.text(
            (gap, canvas_height - 30),
            f"Status: {status}",
            fill=status_color,
            font=small_font
        )

        draw.text(
            (
                canvas_width - 350,
                canvas_height - 30
            ),
            "ORB + SIFT + HSV Color",
            fill=(85, 95, 110),
            font=small_font
        )

        # Convert frames to a consistent palette for GIF output.
        frames.append(
            frame.convert("P", palette=Image.Palette.ADAPTIVE, colors=128)
        )

        print(
            f"GIF frame prepared: {index}/{total_results}"
        )

    if not frames:
        raise ValueError(
            "No readable image pairs were available for the GIF."
        )

    frames[0].save(
        output_path,
        save_all=True,
        append_images=frames[1:],
        duration=duration,
        loop=0,
        optimize=True,
        disposal=2
    )

    print(f"Animated GIF saved to: {output_path}")
    print(f"Total frames: {len(frames)}")

    return output_path


